#!/usr/bin/env python3
"""Generate physics/params.js from the force-field files shipped with OpenMM.

  python tools/build_params.py      (needs openmm; only to regenerate, never to run the site)
"""
import json
import xml.etree.ElementTree as ET
from pathlib import Path

import openmm
import openmm.app as app
from openmm.app.internal import customgbforces as gb

DATA = Path(app.__file__).parent / "data"
OUT = Path(__file__).resolve().parent.parent / "physics" / "params.js"
AMINO = "ALA ARG ASN ASP CYS GLN GLU GLY HIS ILE LEU LYS MET PHE PRO SER THR TRP TYR VAL".split()

ff = ET.parse(DATA / "amber14" / "protein.ff14SB.xml").getroot()
templates = {r.get("name"): r for r in ff.find("Residues")}
hydrogens = {r.get("name"): r for r in ET.parse(DATA / "hydrogens.xml").getroot()}
type_info = {t.get("name"): t for t in ff.find("AtomTypes")}
types = sorted(type_info)
index = {t: i for i, t in enumerate(types)}


def type_of(element, key):
    name = element.get(key)
    return index[name] if name else -1  # -1 is the wildcard


def series(element):
    out, n = [], 1
    while element.get(f"k{n}") is not None:
        out.append([int(element.get(f"periodicity{n}")), float(element.get(f"phase{n}")),
                    float(element.get(f"k{n}"))])
        n += 1
    return out


def added_hydrogens(residue, variant, n_terminal):
    """The rules of Modeller.addHydrogens at pH 7."""
    for h in hydrogens[residue].findall("H"):
        if h.get("terminal") and not (n_terminal and "N" in h.get("terminal")):
            continue
        if h.get("variant") and variant not in h.get("variant").split(","):
            continue
        if not h.get("variant") and float(h.get("maxph", "99")) < 7:
            continue
        yield h.get("name"), h.get("parent")


residues = {}
for residue in AMINO:
    for base in {"HIS": ["HIE"], "CYS": ["CYS", "CYX"]}.get(residue, [residue]):
        for prefix in ("", "N", "C"):
            template = templates[prefix + base]
            atoms = template.findall("Atom")
            names = [a.get("name") for a in atoms]
            added = []
            for name, parent in added_hydrogens(residue, base, prefix == "N"):
                # Modeller calls the first N-terminal hydrogen H; the template calls it H1.
                tname = name if name in names else "H1"
                added.append([name, parent, names.index(tname)])
            heavy = {a.get("name"): i for i, a in enumerate(atoms)
                     if type_info[a.get("type")].get("element") != "H"}
            assert len(heavy) + len(added) == len(atoms), prefix + base
            assert len({i for *_, i in added}) == len(added), prefix + base
            residues[prefix + base] = {
                "atoms": [[index[a.get("type")], float(a.get("charge"))] for a in atoms],
                "heavy": heavy,
                "hydrogens": added,
                "bonds": [[names.index(b.get("atomName1")), names.index(b.get("atomName2"))]
                          for b in template.findall("Bond")],
            }

nonbonded = ff.find("NonbondedForce")
lj = {a.get("type"): [float(a.get("sigma")), float(a.get("epsilon"))] for a in nonbonded.findall("Atom")}
torsion = ff.find("PeriodicTorsionForce")
assert torsion.get("ordering") == "amber"
gbn2 = gb.GBSAGBn2Force

params = {
    "openmm": openmm.version.short_version,
    "elements": [type_info[t].get("element") for t in types],
    "lj": [lj[t] for t in types],
    "scale14": [float(nonbonded.get("coulomb14scale")), float(nonbonded.get("lj14scale"))],
    "residues": residues,
    "bonds": [[type_of(b, "type1"), type_of(b, "type2"), float(b.get("length")), float(b.get("k"))]
              for b in ff.find("HarmonicBondForce")],
    "angles": [[*(type_of(a, f"type{i}") for i in (1, 2, 3)), float(a.get("angle")), float(a.get("k"))]
               for a in ff.find("HarmonicAngleForce")],
    "propers": [[*(type_of(t, f"type{i}") for i in (1, 2, 3, 4)), series(t)]
                for t in torsion.findall("Proper")],
    "impropers": [[*(type_of(t, f"type{i}") for i in (1, 2, 3, 4)), series(t)]
                  for t in torsion.findall("Improper")],
    "gb": {
        "elements": {e.symbol: [gb._SCREEN_PARAMETERS[e][2], *p]
                     for e, p in gbn2._atom_params.items() if e.symbol in "HCNOS"},
        "m0": list(gb.m0),
        "d0": list(gb.d0),
    },
}
OUT.write_text("// Generated by tools/build_params.py from OpenMM's amber14/protein.ff14SB.xml and GBn2\n"
               "// tables. Do not edit. Origin and licences: ../NOTICE.txt\n"
               "export default " + json.dumps(params, separators=(",", ":")) + ";\n", encoding="utf-8")
print(OUT, OUT.stat().st_size, "bytes")
